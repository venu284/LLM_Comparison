class UnparsedTaskId(ValueError):
    """A task id no family rule matches. Add a rule; never guess."""


def _apply(rules, s: str, task_id: str) -> str:
    for pattern, fixed in rules:
        m = pattern.fullmatch(s)
        if m:
            return fixed if fixed is not None else m.group("f")
    raise UnparsedTaskId(task_id)


def parse_family(task_id: str) -> str:
    """Family of a CodeRouterBench task id, from the id alone."""
    if task_id.startswith(("new64::", "old112::")):
        return _apply(OOD_RULES, task_id, task_id)
    m = re.fullmatch(r"dim\d+_(.+)", task_id)
    if not m:
        raise UnparsedTaskId(task_id)
    return _apply(ID_RULES, m.group(1), task_id)


def build_table(root: Path) -> pd.DataFrame:
    """Per-id family table from the pinned release CSVs under `root` (external/CodeRouterBench)."""
    parts = []
    for split, name in ID_SPLIT_FILES.items():
        t = pd.read_csv(root / name, usecols=["task_id", "dimension"]).drop_duplicates("task_id")
        parts.append(t.assign(split=split, split_kind="id"))
    ood = pd.read_csv(root / OOD_FILE, usecols=["task_id", "dimension", "bench"])
    ood = ood.drop_duplicates("task_id")
    parts.append(ood.drop(columns="bench").assign(split="ood", split_kind="ood"))
    t = pd.concat(parts, ignore_index=True)
    if t.task_id.duplicated().any():
        raise ValueError("a task id appears in more than one split")
    t["family"] = [parse_family(x) for x in t.task_id]
    return t[TABLE_COLUMNS].sort_values(["split_kind", "family", "task_id"], ignore_index=True)


def family_counts(table: pd.DataFrame) -> dict[str, Family]:
    out = {}
    for fam, g in table.groupby("family", sort=True):
        kinds, dims = g.split_kind.unique(), g.dimension.unique()
        if len(kinds) != 1 or len(dims) != 1:
            raise ValueError(f"family {fam} spans split kinds {kinds} or dimensions {dims}")
        n = g.split.value_counts()
        out[fam] = Family(kinds[0], dims[0], int(n.get("probing", 0)), int(n.get("id_test", 0)),
                          int(n.get("ood", 0)))
    return out


def load_table() -> pd.DataFrame:
    """The committed per-id family table."""
    return pd.read_csv(TABLE_CSV, dtype=str, keep_default_na=False)


_FAMILY_BY_ID: dict[str, str] | None = None


def family_of(task_id: str) -> str:
    """Family of a task id, looked up in the committed table (parsed if the id is not in it)."""
    global _FAMILY_BY_ID
    if _FAMILY_BY_ID is None:
        t = load_table()
        _FAMILY_BY_ID = dict(zip(t.task_id, t.family))
    fam = _FAMILY_BY_ID.get(task_id)
    return fam if fam is not None else parse_family(task_id)


def families_under(min_tasks: int, split_kind: str = "id") -> dict[str, Family]:
    return {k: f for k, f in FAMILIES.items() if f.split_kind == split_kind and f.n_tasks < min_tasks}


def _render_families(counts: dict[str, Family]) -> str:
    lines = []
    for k, f in counts.items():
        lines.append(f"    {k!r}: Family({f.split_kind!r}, {f.dimension!r}, {f.n_probing}, "
                     f"{f.n_id_test}, {f.n_ood}),")
    return "\n".join(lines)



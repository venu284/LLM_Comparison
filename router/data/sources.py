# OOD ids carry their batch and bench: `new64::<bench>::<id>` or `old112::<repo>__<repo>-<n>`.
# The release's `bench` column is the source of truth; these rules reproduce it from the id and a
# data-gated test checks they agree.
OOD_RULES: list[tuple[re.Pattern, str | None]] = [
    (re.compile(r"new64::(?P<f>featurebench|longcli|swe_ci)::\S+"), None),
    (re.compile(r"old112::\S+"), "old112"),
]



    (re.compile(rf"(?P<f>he_completion|he_testgen|humaneval)_HumanEval_{_N}"), None),
    (re.compile(rf"(?P<f>bugs2fix_sup|codexglue_sup|debugbench_sup|mbpp_completion|mbpp_testgen"
                rf"|bugs2fix|codexglue|debugbench|mbpp|canitedit|cruxeval|ds1000)_{_N}"), None),

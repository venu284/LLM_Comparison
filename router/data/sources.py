"""S1.1: the task-id-to-family table (CLAIMS S0.13: a group is a family).

A family is the source benchmark a task comes from, at the granularity the router explores (O9).
Every CodeRouterBench task id, ID (probing and ID-test) and OOD, maps to exactly one family in
`FAMILIES`. The mapping is parsed from the id by one explicit rule per id pattern; an id no rule
matches raises instead of falling through, which is how the old `coderouterbench.source_of`
produced 572 single-task "families".

The per-id table is committed as `task_families.csv` next to this module, so the frozen list and
its tests do not need `external/`. Regenerate it from the pinned release with
`python -m router.data.sources --write`; a data-gated test checks the two agree.

Family granularity is the user's decision. Families under `MIN_FAMILY_TASKS` are listed in
`PENDING_USER_DECISION` until the user rules on them; nothing here merges families.
"""

